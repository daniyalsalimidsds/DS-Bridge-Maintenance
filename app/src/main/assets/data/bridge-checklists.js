  function itemApplies(categoryId, item, tags) {
    const name = normalize(item.name);
    if (categoryId === 'municipal_complement') {
      const n=item.municipalNumber;
      if(n<=41 && !tags.has('road') && !tags.has('incomplete')) return false;
      if(n>=61 && n<=78 && !tags.has('pier') && !tags.has('abutment') && !tags.has('incomplete')) return false;
      if(n>=56 && n<=60 && !tags.has('bearing') && !tags.has('incomplete')) return false;
    }
    if (categoryId === 'road_pavement') {
      if (tags.has('asphalt-pavement')) return !/روسازی بتنی/.test(name);
      if (tags.has('concrete-pavement')) return !/آسفالت|قیرزدگی|پوست سوسماری|شن زدگی/.test(name);
      return !/آسفالت|قیرزدگی|پوست سوسماری|شن زدگی|روسازی بتنی/.test(name);
    }
    if (categoryId === 'rail_fasteners') {
      if (tags.has('direct-track')) return !/تراورس|بالاست/.test(name) || /بست مستقیم/.test(name);
      if (tags.has('ballasted-track')) return !/بست مستقیم ریل به عرشه بدون بالاست/.test(name);
    }
    if (categoryId === 'rail_safety' && !tags.has('barrier') && !tags.has('sidewalk')) {
      return !/نرده|حفاظ سقوط|صفحات پوششی پیاده رو/.test(name);
    }
    if (categoryId === 'barriers') {
      if (!tags.has('barrier') && /جان پناه|نرده|حفاظ|ارتفاع.*بازشو|برخورد.*سیستم حفاظ/.test(name)) return false;
      if (!tags.has('sidewalk') && /پیاده رو|جزیره میانی/.test(name)) return false;
    }
    return true;
  }

  function checklistsForBridge(bridge) {
    const tags = profileTags(bridge);
    const materialCategories = CATALOG.filter(item => MATERIAL_CATEGORY_IDS.has(item.id));
    const baseCategories = CATALOG
      .filter(item => !MATERIAL_CATEGORY_IDS.has(item.id))
      .filter(item => item.tags.some(tag => tags.has(tag)))
      .map(item => ({ ...item, items: item.items.filter(entry => itemApplies(item.id, entry, tags)) }))
      .filter(item => item.items.length);
    const scopedMaterialCategories = materialScopes(bridge).flatMap(scope => materialCategories
      .filter(category => category.tags.some(tag => scope.tags.has(tag)))
      .map(category => ({
        ...category,
        id: `${category.id}--${scope.sectionId}`,
        name: `${category.name} — ${scope.label}`,
        items: category.items.map(entry => ({ ...entry, id: `${entry.id}--${scope.sectionId}` })),
      })));
    let categoryNumber = 1;
    return [...baseCategories, ...scopedMaterialCategories].map(item => {
      const code = String(categoryNumber++);
      return {
        id: item.id,
        name: item.name,
        code,
        refs: item.refs,
        items: item.items.map((entry, index) => ({ ...entry, code: `${code}.${index + 1}`, categoryName:item.name, scoring:window.BridgeScoring?.definition(entry,item.name) })),
      };
    });
  }

