  function normalize(value) {
    return String(value == null ? '' : value)
      .replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/\u200c/g, ' ')
      .replace(/\s+/g, ' ').trim().toLowerCase();
  }

  function schemaFieldLabel(fieldId) {
    const sections = window.BRIDGE_PROFILE_SCHEMA?.sections || [];
    for (const section of sections) {
      const field = (section.fields || []).find(item => item.id === fieldId);
      if (field) return field.label;
    }
    return '';
  }

  function profileEntries(bridge) {
    return Object.entries(bridge?.profile || {}).map(([id, value]) => ({
      id,
      label: schemaFieldLabel(id),
      value: String(value == null ? '' : value),
    }));
  }

  function profileEntryActive(bridge, entry) {
    if (!entry) return false;
    const entries = profileEntries(bridge);
    const specialPresence = normalize(entries.find(item => item.label === 'وجود سیستم ویژه؟')?.value || '');
    const explicitlyNoCable = /وجود ندارد|خیر/.test(specialPresence);
    const cableOnlyField = ['سیستم سازه‌ای اصلی', 'نوع سیستم عرشه'].includes(entry.label)
      && /ترکه|معلق|پل کابلی/.test(normalize(entry.value));
    return !(explicitlyNoCable && cableOnlyField);
  }

  function profileValue(bridge, label) {
    const entry = profileEntries(bridge).find(item => item.label === label);
    return profileEntryActive(bridge, entry) ? entry.value : '';
  }

  function sectionActive(bridge, sectionId) {
    const entries = profileEntries(bridge).filter(item => item.id.startsWith(sectionId + '__'));
    const presence = entries.find(item => /وجود/.test(item.label));
    if (presence && /وجود ندارد|خیر/.test(normalize(presence.value))) return false;
    return entries.some(item => item.value.trim() && !/نامشخص|نیازمند بررسی/.test(normalize(item.value)));
  }

  function profileTags(bridge) {
    const entries = profileEntries(bridge);
    const filledEntries = entries.filter(item => item.value.trim() && profileEntryActive(bridge, item) && sectionActive(bridge,item.id.split('__')[0]));
    // Labels are deliberately excluded: a label such as «کابل/سیستم اصلی» must
    // never turn a bridge with value «فاقد کابل اصلی» into a cable-stayed bridge.
    const text = normalize(filledEntries.map(item => item.value).join(' | '));
    const usage = normalize(profileValue(bridge, 'کاربری اصلی'));
    const tags = new Set(['always']);
    if (usage.includes('راه آهن')) tags.add('railway');
    else if (usage.includes('راه') || usage.includes('شهری') || usage.includes('موارد ویژه')) tags.add('road');
    if (/بتن/.test(text)) tags.add('concrete');
    if (/پیش تنیده|پس کشیده/.test(text)) tags.add('prestressed');
    if (/فولاد|فلزی|چدنی|ریل/.test(text)) tags.add('steel');
    if (/بنایی|سنگ|آجر/.test(text)) tags.add('masonry');
    if (/چوب/.test(text)) tags.add('timber');
    if (/مختلط|کامپوزیت/.test(text)) tags.add('composite');
    if (/frp|الیاف/.test(text)) tags.add('frp');
    if (/ارتوتروپیک/.test(text)) tags.add('orthotropic');
    if (/خرپا/.test(text)) tags.add('truss');
    if (/قوس|طاق/.test(text)) tags.add('arch');
    const structuralSystem = normalize(profileValue(bridge, 'سیستم سازه‌ای اصلی'));
    const deckSystem = normalize(profileValue(bridge, 'نوع سیستم عرشه'));
    const specialPresence = normalize(profileValue(bridge, 'وجود سیستم ویژه؟'));
    const cableSystem = normalize(profileValue(bridge, 'کابل/سیستم اصلی'));
    const specialCableExplicitlyAbsent = /وجود ندارد|خیر/.test(specialPresence);
    const explicitCableBridge = /ترکه|معلق/.test(structuralSystem) || /پل کابلی/.test(deckSystem);
    const activeSpecialCable = !specialCableExplicitlyAbsent
      && /کابلی|معلق/.test(cableSystem) && !/فاقد/.test(cableSystem);
    // An explicit «وجود ندارد» is authoritative and also neutralizes stale
    // cable-related values left by an older profile edit.
    if (!specialCableExplicitlyAbsent && (explicitCableBridge || activeSpecialCable)) tags.add('cable');
    if (/جعبه|سلولی|مجوف/.test(text)) tags.add('box');
    if (/تیر|شاه تیر|تیرورق/.test(text)) tags.add('girder');
    if (/کالورت|آبرو|لوله/.test(structuralSystem + ' ' + deckSystem)) tags.add('culvert');
    const sectionMap = {
      '05_عرشه_ابرسازه': 'deck', '06_کف_عرشه_دال': 'deck',
      '07_پایه_میانی': 'pier', '08_کوله': 'abutment', '09_پی_شمع': 'foundation',
      '10_تکیه_گاه': 'bearing', '11_درز_انبساط': 'joint', '13_زهکشی': 'drainage',
      '14_نرده_جانپناه': 'barrier', '15_پیاده_رو_جزیره': 'sidewalk',
      '16_دال_دسترسی': 'approach', '17_تاسیسات_الحاقی': 'utilities',
      '18_کابل_دیافراگم': 'diaphragm', '19_آبراهه_محیط': 'waterway',
      '20_ترمیم_بهسازی': 'repair', '21_میرایی_جداساز': 'seismic',
    };
    Object.entries(sectionMap).forEach(([sectionId, tag]) => {
      if (sectionActive(bridge, sectionId)) tags.add(tag);
    });
    const bearingText = normalize([
      profileValue(bridge, 'نوع تکیه‌گاه اصلی'),
      profileValue(bridge, 'مصالح/زیرنوع تکیه‌گاه'),
    ].join(' | '));
    if (tags.has('bearing') && /نئوپرن|الاستومر|لاستیک/.test(bearingText)) tags.add('neoprene');
    const pavement = normalize(profileValue(bridge, 'نوع روسازی'));
    if (tags.has('road') && sectionActive(bridge, '12_روسازی_عایق')) {
      tags.add('road-pavement');
      if (pavement.includes('آسفالت')) tags.add('asphalt-pavement');
      else if (pavement.includes('بتن')) tags.add('concrete-pavement');
      else if (pavement.includes('بنایی')) tags.add('masonry-pavement');
      else tags.add('other-road-pavement');
    }
    if (tags.has('railway')) {
      if (pavement.includes('بالاست')) tags.add('ballasted-track');
      if (pavement.includes('ریل مستقیم')) tags.add('direct-track');
    }
    if (!usage || filledEntries.length < 8 || /نامشخص|نیازمند بررسی/.test(text)) tags.add('incomplete');
    return tags;
  }

